def n(name):
    r = R.get(name)
    if r is None or r['비즈니스_있는_날'] == '':
        return None
    return int(r['비즈니스_있는_날'])


def cell(name):
    v = n(name)
    if v is None:
        return '조회 안 됨'
    if v == 0 and '편 없음' in R[name]['상태']:
        return '편 없음'
    return '%d일' % v


def kdates(name):
    """'10/4~5, 10/8~11' → '10월 4~5·8~11일'"""
    s = R[name]['날짜']
    if not s:
        return ''
    bym = collections.OrderedDict()
    for part in s.split(', '):
        m = re.match(r'(\d+)/(\d+)(?:~(?:(\d+)/)?(\d+))?$', part)
        a_m, a_d, b_m, b_d = int(m.group(1)), int(m.group(2)), m.group(3), m.group(4)
        if b_d is None:
            bym.setdefault(a_m, []).append(str(a_d))
        elif b_m is None or int(b_m) == a_m:
            bym.setdefault(a_m, []).append('%d~%d' % (a_d, int(b_d)))
        else:  # 달을 넘는 구간
            cur = dt.date(2026, a_m, a_d)
            end = dt.date(2026, int(b_m), int(b_d))
            while cur <= end:
                last = min(end, dt.date(2026, cur.month % 12 + 1, 1) - dt.timedelta(days=1)) if cur.month < 12 else end
                bym.setdefault(cur.month, []).append(str(cur.day) if cur == last else '%d~%d' % (cur.day, last.day))
                cur = last + dt.timedelta(days=1)
    return ', '.join('%d월 %s일' % (m, '·'.join(v)) for m, v in bym.items())


def table(cities):
    out = ['| 도시 | 가는 편 | 오는 편 |', '|---|---|---|']
    for c in cities:
        out.append('| %s | %s | %s |' % (c, cell('인천→' + c), cell(c + '→인천')))
    return '\n'.join(out)


def dates_lines(names, maxdays=20):
    out = []
    for nm in names:
        v = n(nm)
        if v and v <= maxdays:
            out.append('%s %s' % (nm, kdates(nm)))
    return '\n'.join(out)


